  Future<void> _initializeFavorites() async {
    _prefs = await SharedPreferences.getInstance();
    _favoriteColorNumbers = _prefs?.getStringList('favorites')?.toSet() ?? {};
    debugPrint('Initialized favorites: $_favoriteColorNumbers');
    notifyListeners();
  }

  Color get currentColor => _currentColor;
  Set<String> get favoriteColorNumbers => _favoriteColorNumbers;
  Map<String, List<Map<String, String>>> get allColors => _colors;

  String? getColorHex(String colorNumber) {
    debugPrint('Looking up color number: $colorNumber');
    debugPrint('Available color sets: ${_colors.keys}');

    for (var colors in _colors.values) {
      debugPrint('Checking color set with ${colors.length} colors');
      for (var color in colors) {
        debugPrint('Checking color: ${color['number']} against $colorNumber');
        if (color['number']?.toUpperCase() == colorNumber.toUpperCase()) {
          final value = color['value'];
          debugPrint(
              'Found matching color: ${color['number']} with value: $value');
          if (value != null && value.startsWith('#')) {
            return value;
          }
        }
      }
    }
    debugPrint('No color found for number: $colorNumber');
    return null;
  }

  void setColor(Color color) {
    _currentColor = color;
    notifyListeners();
  }

  Future<void> loadFavorites() async {
    _prefs = await SharedPreferences.getInstance();
    _favoriteColorNumbers = _prefs?.getStringList('favorites')?.toSet() ?? {};
    notifyListeners();
  }

  Future<void> toggleFavorite(String colorNumber) async {
    if (_favoriteColorNumbers.contains(colorNumber)) {
      _favoriteColorNumbers.remove(colorNumber);
    } else {
      _favoriteColorNumbers.add(colorNumber);
    }
    await _prefs?.setStringList('favorites', _favoriteColorNumbers.toList());
    notifyListeners();
  }

  bool isFavorite(String colorNumber) {
    return _favoriteColorNumbers.contains(colorNumber);
  }
